// noCLI is an environment with no Structurizr CLI: the PATH is empty and STRUCTURIZR_CLI is not set.
func noCLI(string) string { return "" }

// freshness checks the freshness of a view in an environment with no Structurizr CLI.
func freshness(t *testing.T, in *views.Inputs, view *views.Definition, git workspace.GitPort) views.FreshnessResult {
	t.Helper()

	tools := &views.Tools{Getenv: noCLI, WorkspaceRoot: in.Workspace.Root}

	return freshnessWithTools(t, &views.FreshnessInput{View: view, Inputs: in, Git: git, Tools: tools, ToolVersion: "test"})
}

// freshnessWithTools checks the freshness of a view with the tools of the input.
func freshnessWithTools(t *testing.T, input *views.FreshnessInput) views.FreshnessResult {
	t.Helper()

	return views.CheckFreshness(t.Context(), input)
}

// committedManifest parses the manifest that is in the committed files at a path.
func committedManifest(t *testing.T, files map[string]string, path string) *views.Manifest {
	t.Helper()

	manifest, err := views.ParseManifest([]byte(files[path]))
	if err != nil {
		t.Fatal(err)
	}

	return manifest
}

// Scenario "Inputs unchanged": freshness passes and says that it regenerated.
func TestFreshnessInputsUnchanged(t *testing.T) {
	t.Parallel()

	in := testInputs(t, "HTTPS", containerView("payments-container"))
	view := &in.Workspace.Views[0]

	result := freshness(t, in, view, gitAt(committedFiles(t, in, view)))

	requireEq(t, "status", result.Status, views.StatusPass)
	requireEq(t, "verification", result.Verification, views.VerificationRegenerated)
	requireEq(t, "reasons", len(result.Reasons), 0)

	assertEq(t, "contract changed", result.ContractChanged, false)
	assertEq(t, "differing digests", len(result.DifferingDigests), 0)
	assertEq(t, "manifest differences", len(result.ManifestDifferences), 0)

	g := generate(t, in, view)
	assertEq(t, "semantic digest", result.SemanticDigest, g.Digests.Semantic)

	requireEq(t, "artifacts", len(result.Artifacts), 1)
	assertEq(t, "artifact status", result.Artifacts[0].Status, views.StatusPass)
	assertEq(t, "artifact digest", result.Artifacts[0].Digest, g.DSLDigest())
}

// Scenario "Manifest edited by hand": the user edits the manifest so that it claims the current digests, but the
// committed artifact is still the stale one. The regenerated bytes differ from the artifact: violation.
func TestFreshnessManifestEditedByHand(t *testing.T) {
	t.Parallel()

	stale := testInputs(t, "HTTPS", containerView("payments-container"))
	view := &stale.Workspace.Views[0]
	files := committedFiles(t, stale, view)

	current := testInputs(t, "gRPC", containerView("payments-container"))
	hand := committedFiles(t, current, &current.Workspace.Views[0])

	// The stale artifact stays; the manifest is the one that matches the current inputs and the stale artifact's digest.
	manifest := committedManifest(t, hand, view.ManifestPath())
	manifest.Outputs[0].Digest = views.ArtifactDigest([]byte(files[view.Output.Path]))
	files[view.ManifestPath()] = string(mustMarshal(t, manifest))

	result := freshness(t, current, &current.Workspace.Views[0], gitAt(files))

	requireEq(t, "status", result.Status, views.StatusViolation)
	requireHas(t, "reasons", result.Reasons, views.ReasonArtifactDiffers)

	// The digests of the manifest are the current ones, and the manifest only repeats them: no pass.
	assertEq(t, "the hand-edited digests differ from the recomputed ones", len(result.DifferingDigests), 0)
}

// Scenario "Input changed": a relationship that the view depicts changes and the artifact is not regenerated. The
// finding lists the input digests that differ. (A newer modification time is no evidence: nothing here reads one.)
func TestFreshnessInputChanged(t *testing.T) {
	t.Parallel()

	before := testInputs(t, "HTTPS", containerView("payments-container"))
	files := committedFiles(t, before, &before.Workspace.Views[0])

	after := testInputs(t, "gRPC", containerView("payments-container"))

	result := freshness(t, after, &after.Workspace.Views[0], gitAt(files))

	requireEq(t, "status", result.Status, views.StatusViolation)
	requireHas(t, "reasons", result.Reasons, views.ReasonInputsChanged)

	assertHas(t, "differing digests", result.DifferingDigests, views.DigestModel)
	assertHas(t, "differing digests", result.DifferingDigests, views.DigestSemantic)
	assertLacks(t, "differing digests", result.DifferingDigests, views.DigestBindings)

	// The committed DSL still shows the old protocol.
	assertHas(t, "reasons", result.Reasons, views.ReasonArtifactDiffers)
}

// Scenario "Generator cannot run": an export needs the Structurizr CLI and the CLI is missing. The freshness of
// that artifact is unknown with the reason, and the view is not `pass`.
func TestFreshnessGeneratorCannotRun(t *testing.T) {
	t.Parallel()

	view := containerView("payments-container")
	view.Output.Exports = []views.Export{{Format: "mermaid", Path: "docs/architecture/views/payments-container.mmd"}}
	in := testInputs(t, "HTTPS", view)

	result := freshness(t, in, &in.Workspace.Views[0], gitAt(committedFiles(t, in, &in.Workspace.Views[0])))

	requireEq(t, "status", result.Status, views.StatusUnknown)
	requireHas(t, "reasons", result.Reasons, views.ReasonGeneratorUnavailable)

	requireEq(t, "artifacts", len(result.Artifacts), 2)
	assertEq(t, "dsl status", result.Artifacts[0].Status, views.StatusPass)
	assertEq(t, "export status", result.Artifacts[1].Status, views.StatusUnknown)

	// A CLI that did not run has no version.
	assertEq(t, "structurizr version", result.StructurizrVersion, "")

	// A violation of the DSL is not hidden by the unknown export.
	changed := testInputs(t, "gRPC", view)
	got := freshness(t, changed, &changed.Workspace.Views[0], gitAt(committedFiles(t, in, &in.Workspace.Views[0])))
	assertEq(t, "status with a changed input", got.Status, views.StatusViolation)
}

// A CLI that passes the version check and then fails every export leaves no regenerated export. The manifest
// comparison must not dereference a missing `generator.structurizr`: the freshness is an error, not a panic.
func TestFreshnessEveryExportFailsAfterTheVersionCheck(t *testing.T) {
	t.Parallel()

	if runtime.GOOS == "windows" {
		t.Skip("the fake CLI is a shell script")
	}

	dir := t.TempDir()
	script := "#!/bin/sh\nif [ \"$1\" = version ]; then echo " + projection.PinnedStructurizrCLI + "; exit 0; fi\nexit 1\n"

	if err := os.WriteFile(filepath.Join(dir, "structurizr"), []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}

	view := containerView("payments-container")
	view.Output.Exports = []views.Export{{Format: "mermaid", Path: "docs/architecture/views/payments-container.mmd"}}
	in := testInputs(t, "HTTPS", view)
	def := &in.Workspace.Views[0]
	tools := &views.Tools{
		Getenv:        func(key string) string { return map[string]string{"PATH": dir}[key] },
		WorkspaceRoot: in.Workspace.Root,
	}

	result := freshnessWithTools(t, &views.FreshnessInput{View: def, Inputs: in, Git: gitAt(committedFiles(t, in, def)), Tools: tools, ToolVersion: "test"})

	requireEq(t, "status", result.Status, views.StatusError)
	requireHas(t, "reasons", result.Reasons, views.ReasonGeneratorFailed)
	assertEq(t, "version", result.StructurizrVersion, projection.PinnedStructurizrCLI)
}

// Scenario "Contract version bump": the committed manifest has an old contract version.
func TestFreshnessContractVersionBump(t *testing.T) {
	t.Parallel()

	in := testInputs(t, "HTTPS", containerView("payments-container"))
	view := &in.Workspace.Views[0]
	files := committedFiles(t, in, view)

	manifest := committedManifest(t, files, view.ManifestPath())
	manifest.Inputs.ProjectionContract = "concordia-view-projection/0"
	files[view.ManifestPath()] = string(mustMarshal(t, manifest))

	result := freshness(t, in, view, gitAt(files))

	assertEq(t, "status", result.Status, views.StatusViolation)
	assertEq(t, "contract changed", result.ContractChanged, true)
	assertHas(t, "reasons", result.Reasons, views.ReasonContractChanged)
}

// Scenario "Authored view": freshness is not applicable and the digest of the source is recorded.
func TestFreshnessAuthoredView(t *testing.T) {
	t.Parallel()

	authored := authoredAt("payments-authored", "docs/arch/payments.md")
	in := testInputs(t, "HTTPS", authored)

	const source = "# Payments\n"

	result := freshness(t, in, &in.Workspace.Views[0], gitAt(map[string]string{"docs/arch/payments.md": source}))

	requireEq(t, "status", result.Status, views.StatusNotApplicable)
	requireEq(t, "verification", result.Verification, "")

	requireEq(t, "artifacts", len(result.Artifacts), 1)
	assertEq(t, "artifact path", result.Artifacts[0].Path, "docs/arch/payments.md")
	assertEq(t, "artifact digest", result.Artifacts[0].Digest, views.ArtifactDigest([]byte(source)))
}

