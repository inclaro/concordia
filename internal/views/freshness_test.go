// pinnedCLIFiles are the committed files of a view whose exports the pinned CLI rendered, with the manifest
// that records them.
func pinnedCLIFiles(t *testing.T, g *views.Generated, def *views.Definition, tools *views.Tools) map[string]string {
	t.Helper()

	run := views.RenderExports(t.Context(), g, tools)
	requireEq(t, "version", run.Version, projection.PinnedStructurizrCLI)
	requireEq(t, "outcomes", len(run.Outcomes), 2)

	files := map[string]string{def.Output.Path: string(g.DSL)}
	artifacts := make([]views.ExportArtifact, 0, len(run.Outcomes))

	for _, o := range run.Outcomes {
		if o.Err != nil {
			t.Fatal(o.Err)
		}

		files[o.Artifact.Path] = string(o.Artifact.Data)
		artifacts = append(artifacts, o.Artifact)
	}

	files[def.ManifestPath()] = string(mustMarshal(t, views.BuildManifest(g, &views.ManifestOptions{
		ToolVersion: "test", StructurizrVersion: run.Version, Exports: artifacts,
	})))

	return files
}

// With the pinned CLI the exports are regenerated and compared. The test needs the CLI and is skipped without it.
func TestFreshnessRegeneratesExportsWithThePinnedCLI(t *testing.T) {
	t.Parallel()

	cli, ok := projection.FindCLI(os.Getenv)
	if !ok {
		t.Skip("no Structurizr CLI")
	}

	if _, err := projection.VerifyPinned(t.Context(), cli, os.Getenv); err != nil {
		t.Skipf("the Structurizr CLI is not the pinned one: %v", err)
	}

	view := containerView("payments-container")
	view.Output.Exports = []views.Export{
		{Format: "mermaid", Path: "docs/architecture/views/payments-container.mmd"},
		{Format: "json", Path: "docs/architecture/views/payments-container.json"},
	}
	in := testInputs(t, "HTTPS", view)
	def := &in.Workspace.Views[0]
	tools := &views.Tools{Getenv: os.Getenv, WorkspaceRoot: in.Workspace.Root}

	files := pinnedCLIFiles(t, generate(t, in, def), def, tools)

	input := &views.FreshnessInput{View: def, Inputs: in, Git: gitAt(files), Tools: tools, ToolVersion: "test"}

	result := freshnessWithTools(t, input)
	requireEq(t, "status", result.Status, views.StatusPass)
	requireEq(t, "structurizr version", result.StructurizrVersion, projection.PinnedStructurizrCLI)

	files["docs/architecture/views/payments-container.mmd"] += "extra\n"

	edited := freshnessWithTools(t, input)
	assertEq(t, "an edited export: status", edited.Status, views.StatusViolation)
	assertEq(t, "an edited export: artifact status", edited.Artifacts[1].Status, views.StatusViolation)
}
