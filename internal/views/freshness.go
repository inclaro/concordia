// VerificationRegenerated is the verification of freshness: the check recomputed every input digest and regenerated
// the artifact. It is the only way to `pass`; a digest of the manifest is never read as truth.
const VerificationRegenerated = "regenerated"

// The reasons of a freshness result.
const (
	// ReasonContractChanged: the manifest was made with other versions of the digest algorithm or of the
	// projection contract (spec "A digest contract change forces regeneration").
	ReasonContractChanged = "digest contract changed"
	// ReasonInputsChanged: the recomputed input digests differ from the manifest; DifferingDigests lists them.
	ReasonInputsChanged = "input digests differ"
	// ReasonManifestDiffers: another field of the manifest differs from the recomputed manifest.
	ReasonManifestDiffers = "manifest differs from the recomputed manifest"
	// ReasonArtifactDiffers: the committed artifact is not the regenerated one.
	ReasonArtifactDiffers = "artifact differs from the regenerated bytes"
	// ReasonArtifactDigestDiffers: the digest of the committed artifact is not the digest in the manifest.
	ReasonArtifactDigestDiffers = "artifact digest differs from the manifest"
	// ReasonGeneratorUnavailable: an export could not be regenerated (CLI missing, not the pinned version).
	ReasonGeneratorUnavailable = "generator cannot run"
	// ReasonIncludeUnavailable: an allowed include of the DSL cannot be read (spec "Unavailable allowed include").
	ReasonIncludeUnavailable = "include not available"
	// ReasonGeneratorFailed: the generation failed for another reason.
	ReasonGeneratorFailed = "generation failed"
	// ReasonCommittedUnavailable: the artifact or the manifest is not in the tracked revision, so there is
	// nothing to compare (presence reports the absence).
	ReasonCommittedUnavailable = "committed artifact not available"
)

// ArtifactFreshness is the freshness of one artifact of a generated view, or the digest of the source of an
// authored view.
type ArtifactFreshness struct {
	Path   string `json:"path"`
	Format string `json:"format"`
	// Digest is the digest of the committed bytes. Empty when the file is not in the tracked revision.
	Digest string `json:"digest,omitempty"`
	// RegeneratedDigest is the digest of the regenerated canonical bytes. Empty when they could not be made.
	RegeneratedDigest string `json:"regeneratedDigest,omitempty"`
	Status            Status `json:"status"`
	// Detail holds the message that explains the first reason.
	Detail string `json:"detail,omitempty"`
	// Reasons are plain phrases.
	Reasons []string `json:"reasons"`
}

// FreshnessResult is the result of the freshness check of one view.
type FreshnessResult struct {
	Status Status
	// Verification is VerificationRegenerated when the inputs were recomputed and the artifacts regenerated;
	// empty for an authored view and when there was nothing to compare.
	Verification string
	// SemanticDigest is the recomputed semantic digest ("" when it could not be computed).
	SemanticDigest string
	// ManifestPath is the path of the manifest of a generated view.
	ManifestPath string
	// StructurizrVersion is the CLI version that regenerated an export. It goes in the run manifest toolchain.
	StructurizrVersion string
	// Reasons are the plain phrases of the Reason constants, sorted.
	Reasons []string
	// DifferingDigests names the input digests (Digest* constants) that differ from the manifest.
	DifferingDigests []string
	// ManifestDifferences name the other fields of the manifest that differ.
	ManifestDifferences []string
	// Artifacts are the DSL and the exports of a generated view, or the source of an authored one.
	Artifacts []ArtifactFreshness
	// ContractChanged says that the manifest has other contract versions than this Concordia. A later capability
	// reads it for a conservative reassessment (design D15).
	ContractChanged bool
}

// FreshnessInput is the input of CheckFreshness.
type FreshnessInput struct {
	View   *Definition
	Inputs *Inputs
	Git    workspace.GitPort
	Tools  *Tools
	// ToolVersion is the Concordia version. It is provenance: it is not compared with the manifest.
	ToolVersion string
}

// CheckFreshness decides whether the committed artifacts of a view are current (design D8). For a generated view
// it reads the manifest and the artifacts of the tracked revision, recomputes the projections and the digests,
// regenerates the DSL in memory and each export with the pinned CLI in the confined runner, and compares bytes
// and digests. It reads no digest of the manifest as truth: there is no way to `pass` from stored digests alone.
//
//   - violation: the manifest has other contract versions, an input digest differs, another manifest field
//     differs, or a committed artifact is not the regenerated one;
//   - unknown: an export cannot be regenerated (the CLI is missing or is not the pinned version, an allowed include
//     cannot be read), the revision cannot be listed, or a committed file is not in it;
//   - error: the generation failed;
//   - not-applicable: the view is authored (the source digest is recorded).
func CheckFreshness(ctx context.Context, in *FreshnessInput) FreshnessResult {
	if in.View.Origin == OriginAuthored {
		return authoredFreshness(ctx, in)
	}

	run := &freshnessRun{in: in, result: FreshnessResult{ManifestPath: in.View.ManifestPath(), Reasons: []string{}, Artifacts: []ArtifactFreshness{}}}

	return run.check(ctx)
}

// authoredFreshness: an authored view has no generation freshness; the digest of its source is recorded.
func authoredFreshness(ctx context.Context, in *FreshnessInput) FreshnessResult {
	result := FreshnessResult{Status: StatusNotApplicable, Reasons: []string{}, Artifacts: []ArtifactFreshness{}}

	if in.View.Source == nil {
		return result
	}

	artifact := ArtifactFreshness{Path: in.View.Source.Path, Format: in.View.Source.Format, Status: StatusNotApplicable, Reasons: []string{}}

	if data, ok := committedFile(ctx, in.Git, in.View.Source.Path); ok {
		artifact.Digest = ArtifactDigest(data)
	}

	result.Artifacts = append(result.Artifacts, artifact)

	return result
}

// committedFile reads a file of the tracked revision. It reports false when there is no revision, the file is
// not in it, or Git fails.
func committedFile(ctx context.Context, git workspace.GitPort, p string) (content []byte, ok bool) {
	revision, err := git.Revision(ctx)
	if err != nil || revision == "" {
		return nil, false
	}

	data, found, err := git.ShowFile(ctx, revision, p)
	if err != nil || !found {
		return nil, false
	}

	return data, true
}

type freshnessRun struct {
	in *FreshnessInput
	// manifest is the committed manifest, once it was read and parsed.
	manifest *Manifest
	revision string
	result   FreshnessResult
}

func (r *freshnessRun) check(ctx context.Context) FreshnessResult {
	view := r.in.View

	revision, err := r.in.Git.Revision(ctx)

	switch {
	case err != nil:
		return r.finish(StatusUnknown, ReasonNoRevision+": cannot read the revision: "+err.Error())
	case revision == "":
		return r.finish(StatusUnknown, ReasonNoRevision+": the workspace is not in a Git repository with a commit")
	}

	r.revision = revision

	generated, err := Generate(r.in.Inputs, view)
	if err != nil {
		return r.finish(StatusError, ReasonGeneratorFailed+": "+err.Error())
	}

	r.result.SemanticDigest = generated.Digests.Semantic
	r.result.Verification = VerificationRegenerated

	exports := RenderExports(ctx, generated, r.in.Tools)
	r.result.StructurizrVersion = exports.Version

	parts := make([]Status, 0, 1+len(view.Output.Exports)+1)
	parts = append(parts, r.compareManifest(ctx, generated, &exports))
	parts = append(parts, r.compareArtifacts(ctx, generated, &exports)...)

	return r.finish(worstStatus(parts), r.result.Reasons...)
}

// finish sets the status and the sorted reasons.
func (r *freshnessRun) finish(status Status, reasons ...string) FreshnessResult {
	r.result.Status = status
	r.result.Reasons = append(r.result.Reasons, reasons...)

	slices.Sort(r.result.Reasons)
	r.result.Reasons = slices.Compact(r.result.Reasons)

	return r.result
}

// worstStatus is the status of a view from the statuses of its parts: a violation is the worst, then an error, then
// unknown. Only parts that all pass give pass.
func worstStatus(parts []Status) Status {
	for _, status := range []Status{StatusViolation, StatusError, StatusUnknown} {
		if slices.Contains(parts, status) {
			return status
		}
	}

	return StatusPass
}

// read gives the committed bytes of a path in the tracked revision; false when it is not there.
func (r *freshnessRun) read(ctx context.Context, target string) (content []byte, found bool, err error) {
	data, found, err := r.in.Git.ShowFile(ctx, r.revision, target)
	if err != nil {
		return nil, false, fmt.Errorf("read %s at revision %s: %w", target, r.revision, err)
	}

	return data, found, nil
}

// compareManifest compares the committed manifest with the manifest that the recomputed inputs give. The revisions,
// the dirty tree and the Concordia version are provenance and are not compared.
func (r *freshnessRun) compareManifest(ctx context.Context, generated *Generated, exports *ExportRun) Status {
	data, found, err := r.read(ctx, r.result.ManifestPath)

	switch {
	case err != nil:
		r.result.Reasons = append(r.result.Reasons, ReasonGeneratorFailed+": "+err.Error())

		return StatusError
	case !found:
		r.result.Reasons = append(r.result.Reasons, ReasonCommittedUnavailable)

		return StatusUnknown
	}

	have, err := ParseManifest(data)
	if err != nil {
		r.result.Reasons = append(r.result.Reasons, ReasonManifestInvalid)

		return StatusViolation
	}

	want := BuildManifest(generated, &ManifestOptions{
		ToolVersion: r.in.ToolVersion, StructurizrVersion: exports.Version, Exports: regenerated(exports),
	})

	status := StatusPass

	if have.ContractChanged() {
		r.result.ContractChanged = true
		r.result.Reasons = append(r.result.Reasons, ReasonContractChanged)
		status = StatusViolation
	}

	if r.result.DifferingDigests = have.DifferingDigests(want); len(r.result.DifferingDigests) > 0 {
		r.result.Reasons = append(r.result.Reasons, ReasonInputsChanged)
		status = StatusViolation
	}

	if r.result.ManifestDifferences = manifestDifferences(have, want, generated.View, exports); len(r.result.ManifestDifferences) > 0 {
		r.result.Reasons = append(r.result.Reasons, ReasonManifestDiffers)
		status = StatusViolation
	}

	r.manifest = have

	return status
}

// regenerated gives the exports that the run could make.
func regenerated(exports *ExportRun) []ExportArtifact {
	var out []ExportArtifact

	for i := range exports.Outcomes {
		if exports.Outcomes[i].Err == nil {
			out = append(out, exports.Outcomes[i].Artifact)
		}
	}

	return out
}

// manifestDifferences names the fields of the committed manifest, apart from the digests, that differ from the
// recomputed manifest. An export that could not be regenerated is compared by its declaration only.
func manifestDifferences(have, want *Manifest, view *Definition, exports *ExportRun) []string {
	var out []string

	add := func(name string, differs bool) {
		if differs {
			out = append(out, name)
		}
	}

	add("schema", have.Schema != want.Schema)
	add("view.id", have.View.ID != want.View.ID)
	add("view.kind", have.View.Kind != want.View.Kind)
	add("view.definitionVersion", have.View.DefinitionVersion != want.View.DefinitionVersion)
	add("view.scope", !slices.Equal(have.View.Scope, want.View.Scope))
	add("view.environment", !equalOptional(have.View.Environment, want.View.Environment))
	add("sources", len(have.Sources) != len(want.Sources))
	add("generator.name", have.Generator.Name != want.Generator.Name)
	add("generator.dslContract", have.Generator.DSLContract != want.Generator.DSLContract)

	haveStructurizr := have.Generator.Structurizr

	switch {
	case len(view.Output.Exports) == 0:
		add("generator.structurizr", haveStructurizr != nil)
	case exports.Version != "":
		add("generator.structurizr", haveStructurizr == nil || *haveStructurizr != ManifestStructurizr{Version: exports.Version, Confinement: ConfinementScrubbedEnv})
	}

	declared := view.OutputPaths()

	for _, o := range have.Outputs {
		add("outputs."+o.Path, !slices.Contains(declared, o.Path))
	}

	for _, wanted := range want.Outputs {
		got, ok := have.Output(wanted.Path)
		add("outputs."+wanted.Path, !ok || got != wanted)
	}

	for i := range exports.Outcomes {
		if exports.Outcomes[i].Err == nil {
			continue
		}

		export := view.Output.Exports[i]
		got, ok := have.Output(export.Path)
		canonical, _ := projection.CanonicalizationFor(projection.ExportFormat(export.Format))
		add("outputs."+export.Path, !ok || got.Format != export.Format || got.Canonicalization != canonical)
	}

	slices.Sort(out)

	return slices.Compact(out)
}

// compareArtifacts compares the committed DSL and each committed export with the regenerated bytes and with the
// digest in the manifest.
func (r *freshnessRun) compareArtifacts(ctx context.Context, generated *Generated, exports *ExportRun) []Status {
	view := r.in.View

	statuses := make([]Status, 0, 1+len(view.Output.Exports))
	statuses = append(statuses, r.artifact(ctx, &ArtifactFreshness{Path: view.Output.Path, Format: FormatDSL}, generated.DSL, nil))

	for i := range exports.Outcomes {
		outcome := &exports.Outcomes[i]
		export := view.Output.Exports[i]
		artifact := &ArtifactFreshness{Path: export.Path, Format: export.Format}

		if outcome.Err != nil {
			statuses = append(statuses, r.artifact(ctx, artifact, nil, outcome.Err))

			continue
		}

		statuses = append(statuses, r.artifact(ctx, artifact, outcome.Artifact.Data, nil))
	}

	return statuses
}

// artifact compares one committed file. want is the regenerated bytes, or nil with the reason that they could not
// be made (failure).
func (r *freshnessRun) artifact(ctx context.Context, artifact *ArtifactFreshness, want []byte, failure error) Status {
	artifact.Reasons = []string{}

	defer func() { r.result.Artifacts = append(r.result.Artifacts, *artifact) }()

	if want != nil {
		artifact.RegeneratedDigest = ArtifactDigest(want)
	}

	data, found, err := r.read(ctx, artifact.Path)

	switch {
	case err != nil:
		return r.fail(artifact, StatusError, ReasonGeneratorFailed, err.Error())
	case !found:
		r.result.Reasons = append(r.result.Reasons, ReasonCommittedUnavailable)
		artifact.Status, artifact.Detail = StatusUnknown, artifact.Path+" is not in revision "+r.revision
		artifact.Reasons = append(artifact.Reasons, ReasonCommittedUnavailable)

		return StatusUnknown
	}

	artifact.Digest = ArtifactDigest(data)
	status := StatusPass

	if r.manifest != nil {
		if recorded, ok := r.manifest.Output(artifact.Path); ok && recorded.Digest != artifact.Digest {
			status = r.fail(artifact, StatusViolation, ReasonArtifactDigestDiffers, artifact.Path)
		}
	}

	switch {
	case failure != nil:
		// The bytes could not be regenerated: the artifact is not verified, and not `pass`.
		reason, detail, failed := classifyExportFailure(failure)
		if status != StatusViolation {
			status = failed
		}

		artifact.Detail = detail
		r.addReason(artifact, reason)
	case !bytes.Equal(data, want):
		status = r.fail(artifact, StatusViolation, ReasonArtifactDiffers, artifact.Path)
	}

	artifact.Status = status

	return status
}

// fail records a reason on the artifact and the result and gives the status.
func (r *freshnessRun) fail(artifact *ArtifactFreshness, status Status, reason, detail string) Status {
	artifact.Status, artifact.Detail = status, detail
	r.addReason(artifact, reason)

	return status
}

func (r *freshnessRun) addReason(artifact *ArtifactFreshness, reason string) {
	artifact.Reasons = append(artifact.Reasons, reason)
	r.result.Reasons = append(r.result.Reasons, reason)
}

// classifyExportFailure gives the reason, the message and the status of an export that could not be regenerated:
// a missing CLI, another version than the pin and an include that cannot be read are `unknown`; anything else is
// an error of the generation.
func classifyExportFailure(err error) (reason, detail string, status Status) {
	var failure *diag.Error

	switch {
	case errors.Is(err, projection.ErrIncludeUnavailable):
		return ReasonIncludeUnavailable, err.Error(), StatusUnknown
	case errors.As(err, &failure) && (failure.Diagnostic.Code == diag.PRJ001 || failure.Diagnostic.Code == diag.DGM004):
		return ReasonGeneratorUnavailable, failure.Diagnostic.Message, StatusUnknown
	}

	return ReasonGeneratorFailed, err.Error(), StatusError
}
